"""Headline summary: size vs debris accuracy for every main model → results/headline.{md,csv} + fig_size_vs_debris.

Sources (all from runs/, single pass, labelled pixels only):
  teacher FP32      p1-A-ckpt<k>-envorig-*            (released checkpoints 1-5)
  students FP32     p2-Blong-w<w>-s<seed>-*, p3-Clong-w<w>-s<seed>-*, p3-F2-w<w>-s<seed>-*   (160 rounds)
                    p2-B-w0.125-s0-*                  (×⅛, 80 rounds only — no 160-round run)
  INT8 (tuned)      p4-H-*-qpctends-*                 (percentile calibration + first/last conv FP32)
  sizes             p4-bench-laptop-* (FP32 state dict), p4-H-* (ONNX INT8 file)
  CPU latency       p4-H-*-qpctends-* ``latency`` (ONNX Runtime, laptop CPU, batch 1)
"""
from __future__ import annotations

import csv
import json
import re
import statistics as st
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
RUNS, RES = REPO / "runs", REPO / "results"
DEBRIS = "Marine Debris"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7", "#e34948"]
INK, INK2, MUTED, GRID = "#0b0b0b", "#52514e", "#898781", "#e6e5e1"
plt.rcParams.update({"font.size": 10, "axes.edgecolor": MUTED, "axes.labelcolor": INK2, "xtick.color": INK2,
                     "ytick.color": INK2, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8,
                     "axes.spines.top": False, "axes.spines.right": False, "legend.frameon": False,
                     "savefig.dpi": 200, "savefig.bbox": "tight"})

# (row label, width, regex over run names, metrics engine) — engine None = training/eval run metrics.json
ROWS = [("Teacher (released, 5 ckpts)", 1.0, r"p1-A-ckpt\d-envorig-\d{8}-\d{4}$", None),
        ("Teacher + INT8", 1.0, r"p4-H-A-ckpt\d-qpctends-\d{8}-\d{4}$", "onnx_int8"),
        ("½ labels only", 0.5, r"p2-Blong-w0\.5-s\d-\d{8}-\d{4}$", None),
        ("½ full method", 0.5, r"p3-F2-w0\.5-s\d-\d{8}-\d{4}$", None),
        ("½ full method + INT8", 0.5, r"p4-H-F2-w0\.5-s\d-qpctends-\d{8}-\d{4}$", "onnx_int8"),
        ("¼ labels only", 0.25, r"p2-Blong-w0\.25-s\d-\d{8}-\d{4}$", None),
        ("¼ debris ×2", 0.25, r"p3-Clong-w0\.25-s\d-\d{8}-\d{4}$", None),
        ("¼ full method", 0.25, r"p3-F2-w0\.25-s\d-\d{8}-\d{4}$", None),
        ("¼ full method + INT8", 0.25, r"p4-H-F2-w0\.25-s\d-qpctends-\d{8}-\d{4}$", "onnx_int8"),
        ("⅛ labels only (80 rounds)", 0.125, r"p2-B-w0\.125-s\d-\d{8}-\d{4}$", None)]


def runs_for(regex: str):
    """Newest complete run per model key (seed or checkpoint), so re-runs replace older ones."""
    out = {}
    for d in sorted(RUNS.iterdir()):
        if re.match(regex, d.name) and (d / "metrics.json").exists():
            m = json.loads((d / "metrics.json").read_text())
            if "test" not in m.get("results", {}):
                continue                                          # val-only tuning runs
            key = re.sub(r"-\d{8}-\d{4}$", "", d.name)
            out[key] = (d, m)
    return list(out.values())


def scores(m: dict, split: str, engine) -> dict:
    r = m["results"][split][engine or "single"]
    db = r["per_class"][DEBRIS]
    return {"debris_f1": 100 * db["f1"], "debris_recall": 100 * db["recall"], "macro_f1": 100 * r["macro_f1"]}


def ms(xs):
    return "" if not xs else (f"{st.mean(xs):.1f} ± {st.stdev(xs):.1f}" if len(xs) > 1 else f"{xs[0]:.1f}")


def main() -> None:
    bench = sorted(RUNS.glob("p4-bench-laptop-*/metrics.json"))[-1]
    fp32_mb = {float(w): v["state_dict_bytes"] / 1e6 for w, v in json.loads(bench.read_text())["models"].items()}
    params = {float(w): v["params"] for w, v in json.loads(bench.read_text())["models"].items()}
    lat = {}
    for d in RUNS.glob("p4-H-*-qpctends-*"):
        m = json.loads((d / "metrics.json").read_text())
        if "latency" in m:
            lat[float(m["width"])] = m["latency"]

    rows, L = [], ["# Headline: model size vs debris accuracy\n",
                   "Generated by `scripts/summarise_headline.py`. Single pass, labelled pixels only; mean ± sd over "
                   "seeds (students) or released checkpoints (teacher), n shown. Students trained 160 rounds "
                   "(LR steps 90/130) unless noted. INT8 = ONNX Runtime static quantization, percentile calibration, "
                   "first/last conv kept FP32 (setting chosen on validation). Size = FP32 PyTorch state dict or INT8 "
                   "ONNX file. CPU latency = ONNX Runtime on the laptop CPU (i7-13620H), batch 1, median ms.\n",
                   "| model | params | size (MB) | n | val debris F1 | test debris F1 | test debris recall | "
                   "val macro-F1 | CPU 1 thread (ms) | CPU 8 threads (ms) |",
                   "|---|---|---|---|---|---|---|---|---|---|"]
    plot = defaultdict(dict)
    for label, w, rx, eng in ROWS:
        found = runs_for(rx)
        if not found:
            L.append(f"| {label} | {params[w]:,} | | 0 | (not run) | | | | | |"); continue
        int8 = eng == "onnx_int8"
        size = st.mean(m["sizes_bytes"]["onnx_int8"] for _, m in found) / 1e6 if int8 else fp32_mb[w]
        v = {s: [scores(m, s, eng) for _, m in found] for s in ("val", "test")}
        key = "onnx_int8" if int8 else "onnx_fp32"
        l1 = f"{lat[w][f'{key}_cpu_1t']['median_ms']:.1f}" if w in lat else ""
        l8 = f"{lat[w][f'{key}_cpu_8t']['median_ms']:.1f}" if w in lat else ""
        cols = [ms([x["debris_f1"] for x in v["val"]]), ms([x["debris_f1"] for x in v["test"]]),
                ms([x["debris_recall"] for x in v["test"]]), ms([x["macro_f1"] for x in v["val"]])]
        L.append(f"| {label} | {params[w]:,} | {size:.2f} | {len(found)} | " + " | ".join(cols) + f" | {l1} | {l8} |")
        rows.append({"model": label, "width": w, "params": params[w], "size_mb": round(size, 3), "n": len(found),
                     "val_debris_f1": cols[0], "test_debris_f1": cols[1], "test_debris_recall": cols[2],
                     "val_macro_f1": cols[3], "cpu_1t_ms": l1, "cpu_8t_ms": l8,
                     "runs": " ".join(d.name for d, _ in found)})
        for s in ("val", "test"):
            xs = [x["debris_f1"] for x in v[s]]
            plot[s][label] = (size, st.mean(xs), st.stdev(xs) if len(xs) > 1 else 0.0)
    L.append("\nLatency is measured once per model size (it does not depend on the weights); "
             "FP32 latency is the ONNX FP32 export of the same model.")
    RES.mkdir(exist_ok=True)
    (RES / "headline.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    with open(RES / "headline.csv", "w", newline="", encoding="utf-8") as f:
        wr = csv.DictWriter(f, fieldnames=list(rows[0].keys())); wr.writeheader(); wr.writerows(rows)

    groups = [("teacher + labels-only students", ["Teacher (released, 5 ckpts)", "½ labels only", "¼ labels only"],
               SERIES[0], "o"),
              ("full-method students", ["½ full method", "¼ full method"], SERIES[1], "s"),
              ("INT8 (teacher, full-method students)", ["Teacher + INT8", "½ full method + INT8",
                                                        "¼ full method + INT8"], SERIES[2], "D")]
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=True)
    for ax, s in zip(axes, ("val", "test")):
        for name, labels, col, mk in groups:
            pts = [plot[s][lb] for lb in labels if lb in plot[s]]
            if pts:
                ax.errorbar([p[0] for p in pts], [p[1] for p in pts], yerr=[p[2] for p in pts], fmt=mk + "-",
                            color=col, lw=1.5, ms=7, mec="white", capsize=3, label=name)
        if "⅛ labels only (80 rounds)" in plot[s]:
            p = plot[s]["⅛ labels only (80 rounds)"]
            ax.plot([p[0]], [p[1]], "o", mfc="none", mec=SERIES[0], ms=7, label="⅛ labels only (80 rounds)")
        ax.set_xscale("log"); ax.set_xlabel("size on disk (MB, log scale)")
        ax.set_title(f"{s} split", color=INK, loc="left")
    axes[0].set_ylabel("Marine Debris F1 (%)")
    h, lb = axes[0].get_legend_handles_labels()
    fig.legend(h, lb, loc="upper center", bbox_to_anchor=(0.5, 0.0), ncol=2)
    for ext in ("png", "pdf"):
        fig.savefig(RES / f"fig_size_vs_debris.{ext}")
    plt.close(fig)
    print("wrote results/headline.md")


if __name__ == "__main__":
    main()
