"""Teacher reliability (KD teacher = released ckpt 5) → results/teacher_reliability.{md,csv}.

Reads the newest full run ``runs/p3-teacherrel-ckpt5-<ts>`` (smoke runs ``-sub<N>`` are skipped), written by
``src/debriskd/teacher_reliability.py``. Single pass, no augmentation, softmax at T = 1.
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUNS, RES = REPO / "runs", REPO / "results"


def pct(x) -> str:
    return "" if x is None else f"{100 * x:.1f}"


def main() -> None:
    runs = sorted(d for d in RUNS.glob("p3-teacherrel-ckpt5-*")
                  if re.match(r"p3-teacherrel-ckpt5-\d{8}-\d{4}$", d.name) and (d / "metrics.json").exists())
    d = runs[-1]
    m = json.loads((d / "metrics.json").read_text())
    tau, R = m["tau"], m["results"]
    splits = [s for s in ("train", "val") if s in R]
    L = ["# Teacher reliability (KD teacher: released checkpoint 5)\n",
         f"Generated by `scripts/summarise_teacher_reliability.py` from `{d.name}`. Single pass, no augmentation, "
         f"softmax at T = 1; confidence = largest class probability; τ = {tau}. The teacher was trained on the train "
         "split, so train numbers are optimistic; val is the fair estimate. Test split not used.\n",
         "## Accuracy on labelled pixels by teacher confidence\n",
         "| confidence | " + " | ".join(f"{s}: share of px | {s}: accuracy" for s in splits) + " |",
         "|---|" + "---|---|" * len(splits)]
    rows = []
    for i, b in enumerate(R[splits[0]]["reliability"]):
        cells = []
        for s in splits:
            r = R[s]["reliability"][i]
            cells += [pct(r["share"]), pct(r["accuracy"])]
            rows.append({"table": "reliability", "split": s, "key": r["conf_bin"], "n": r["n"],
                         "share_pct": pct(r["share"]), "accuracy_pct": pct(r["accuracy"])})
        L.append(f"| {b['conf_bin']} | " + " | ".join(cells) + " |")
    cells = []
    for s in splits:
        hi = [b for b in R[s]["reliability"] if float(b["conf_bin"][1:5]) >= tau]   # bins start at τ = 0.8
        n_hi = sum(b["n"] for b in hi)
        cells += [pct(n_hi / R[s]["labelled_px"]), pct(sum(b["n"] * b["accuracy"] for b in hi) / n_hi)]
    L.append(f"| ≥ τ ({tau}) | " + " | ".join(cells) + " |")
    L.append("| all | " + " | ".join(f"100 | {pct(R[s]['labelled_accuracy'])}" for s in splits) + " |")
    L += ["", f"## Per class, labelled pixels with confidence ≥ τ\n",
          "Coverage = share of the class's labelled pixels on which the teacher is confident; accuracy = how often "
          "the teacher is right on those; precision = how often a confident teacher prediction of that class is right.\n",
          "| class | " + " | ".join(f"{s}: labelled px | {s}: coverage | {s}: accuracy | {s}: precision" for s in splits)
          + " |", "|---|" + "---|---|---|---|" * len(splits)]
    for c in R[splits[0]]["per_class_true"]:
        cells = []
        for s in splits:
            t, p = R[s]["per_class_true"][c], R[s]["per_class_predicted"][c]
            cells += [f"{t['labelled_px']:,}", pct(t["coverage"]), pct(t["accuracy_when_confident"]),
                      pct(p["precision_when_confident"])]
            rows.append({"table": "per_class", "split": s, "key": c, "n": t["labelled_px"],
                         "share_pct": pct(t["coverage"]), "accuracy_pct": pct(t["accuracy_when_confident"]),
                         "precision_pct": pct(p["precision_when_confident"])})
        L.append(f"| {c} | " + " | ".join(cells) + " |")
    L += ["", "## Unlabelled pixels (what the unlabelled-pixel KD term sees)\n",
          "| | " + " | ".join(splits) + " |", "|---|" + "---|" * len(splits),
          "| unlabelled px | " + " | ".join(f"{R[s]['unlabelled_px']:,}" for s in splits) + " |",
          f"| share with confidence ≥ τ | " + " | ".join(pct(R[s]["unlabelled_confident_share"]) for s in splits) + " |"]
    for s in splits:
        h = R[s]["unlabelled_confident_hist"]; n = sum(h.values())
        top = sorted(h.items(), key=lambda kv: -kv[1])
        L.append(f"| {s}: teacher class among confident unlabelled px | "
                 + "; ".join(f"{k} {100 * v / n:.2f}%" for k, v in top if v) + " |" + " |" * (len(splits) - 1))
        for k, v in top:
            rows.append({"table": "unlabelled_hist", "split": s, "key": k, "n": v, "share_pct": f"{100 * v / n:.3f}"})
    RES.mkdir(exist_ok=True)
    (RES / "teacher_reliability.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    keys = ["table", "split", "key", "n", "share_pct", "accuracy_pct", "precision_pct"]
    with open(RES / "teacher_reliability.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=keys); w.writeheader(); w.writerows(rows)
    print("wrote results/teacher_reliability.md")


if __name__ == "__main__":
    main()
