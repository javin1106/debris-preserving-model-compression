"""INT8 summary (setting H) → results/int8.{md,csv}.

Reads runs/p4-H-*/ written by ``src/debriskd/quantize.py`` (smoke runs with --subset are skipped).
Groups: released teachers (A-ckpt1..5) and each student setting/width (e.g. F2-w0.25, seeds pooled).
Accuracy: single pass, labelled pixels only, PyTorch FP32 (CPU) vs ONNX FP32 vs ONNX INT8; the INT8 change is
paired (same model). Latency: ONNX Runtime CPU on the laptop, only where ``--latency`` has been run.
"""
from __future__ import annotations

import csv
import json
import re
import statistics as st
from collections import defaultdict
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
RUNS, RES = REPO / "runs", REPO / "results"
DEBRIS = "Marine Debris"
ENGINES = ("torch_fp32", "onnx_fp32", "onnx_int8")
KEYS = [("debris_f1", "debris F1"), ("debris_recall", "debris recall"), ("debris_precision", "debris precision"),
        ("macro_f1", "macro-F1"), ("mIoU", "mIoU")]


def ms(xs):
    return f"{st.mean(xs):.1f} ± {st.stdev(xs):.1f}" if len(xs) > 1 else f"{xs[0]:.1f}"


def group_of(c: dict) -> str:
    """'Teacher (released ckpts) [variant]' or '<setting>-w<width> [variant]' (seeds pooled)."""
    v = c.get("quantization", {}).get("variant", "plain")
    base = "Teacher (released ckpts)" if c["kind"] == "teacher" else re.sub(r"-s\d+(-q\S+)?$", "", c["tag"])
    return f"{base} [{v}]"


def main() -> None:
    latest = {}
    for d in sorted(RUNS.glob("p4-H-*")):
        if not (d / "metrics.json").exists():
            continue
        c = yaml.safe_load((d / "config.yaml").read_text())
        if c.get("subset"):
            continue
        latest[c["tag"]] = (d, c, json.loads((d / "metrics.json").read_text()))   # newest run per tag wins
    groups = defaultdict(list)
    for tag, v in sorted(latest.items()):
        groups[group_of(v[1])].append((tag, *v))

    rows, L = [], ["# INT8 post-training quantization (setting H)\n",
                   "Generated by `scripts/summarise_int8.py` from `runs/p4-H-*` (`src/debriskd/quantize.py`). "
                   "ONNX Runtime static quantization, QDQ: Conv weights int8 per channel, activations uint8, MinMax "
                   "calibration on 200 training patches (no augmentation); the decoder's NMF steps stay FP32. "
                   "NMF starting bases fixed to the seed-0 draw used by single-pass evaluation. Single pass, labelled "
                   "pixels only. Values are mean ± sd over the models in each group (n shown).\n"]
    for split in ("val", "test"):
        L += [f"## {split}: accuracy\n", "| group | n | engine | " + " | ".join(n for _, n in KEYS) + " |",
              "|---|---|---|" + "---|" * len(KEYS)]
        for g, items in groups.items():
            items = [it for it in items if split in it[3]["results"]]   # tuning runs may score val only
            if not items:
                continue
            vals = defaultdict(lambda: defaultdict(list))
            for tag, d, c, m in items:
                r = m["results"][split]
                for e in ENGINES:
                    db = r[e]["per_class"][DEBRIS]
                    x = {"debris_f1": db["f1"], "debris_recall": db["recall"], "debris_precision": db["precision"],
                         "macro_f1": r[e]["macro_f1"], "mIoU": r[e]["mIoU"]}
                    for k in x:
                        vals[e][k].append(100 * x[k])
                    rows.append({"group": g, "tag": tag, "run_id": d.name, "split": split, "engine": e,
                                 **{k: round(100 * v, 2) for k, v in x.items()}})
            for e in ENGINES:
                L.append(f"| {g} | {len(items)} | {e} | " + " | ".join(ms(vals[e][k]) for k, _ in KEYS) + " |")
            diff = {k: [a - b for a, b in zip(vals["onnx_int8"][k], vals["onnx_fp32"][k])] for k, _ in KEYS}
            L.append(f"| {g} | {len(items)} | **INT8 − FP32** | " + " | ".join(ms(diff[k]) for k, _ in KEYS) + " |")
        L.append("")
    L += ["## Size on disk (MB, per model)\n", "| group | params | PyTorch state dict | ONNX FP32 | ONNX INT8 | INT8 / FP32 |",
          "|---|---|---|---|---|---|"]
    for g, items in groups.items():
        m = items[0][3]; s = m["sizes_bytes"]
        L.append(f"| {g} | {m['params']:,} | {s['torch_state_dict']/1e6:.2f} | {s['onnx_fp32']/1e6:.2f} | "
                 f"{s['onnx_int8']/1e6:.2f} | {s['onnx_int8']/s['onnx_fp32']:.2f} |")
    lat = [(g, tag, m["latency"]) for g, items in groups.items() for tag, d, c, m in items if "latency" in m]
    L += ["", "## CPU latency, ONNX Runtime (laptop, batch 1, ms: median / p90)\n"]
    if lat:
        cols = [k for k in lat[0][2] if k != "protocol"]
        L += ["| model | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
        for g, tag, x in lat:
            L.append(f"| {tag} | " + " | ".join(f"{x[k]['median_ms']:.1f} / {x[k]['p90_ms']:.1f}" for k in cols) + " |")
        L.append(f"\nProtocol: {lat[0][2]['protocol']}")
    else:
        L.append("Not measured yet (run `python -m src.debriskd.quantize --latency <runs>` on an idle laptop).")
    L.append("\nChecks (every run): fixed NMF bases reproduce the seeded forward exactly; ONNX FP32 vs PyTorch max |Δlogit| "
             + ", ".join(f"{t} {v[2]['checks']['onnx_fp32_max_abs_diff_vs_torch']:.1e}" for t, v in latest.items()) + ".")
    RES.mkdir(exist_ok=True)
    (RES / "int8.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    with open(RES / "int8.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    print("wrote results/int8.md")


if __name__ == "__main__":
    main()
