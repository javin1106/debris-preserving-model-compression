"""Phase 3 pilot summary (x0.25, seed 0, untuned KD defaults) → results/kd_pilot.{md,csv}.

Reads runs/: p2-B-w0.25-s0-* (setting B, 80 ep), p2-Blong-w0.25-s0-* (B, 160 ep), p3-{C,D,E,F}-w0.25-s0-*.
Single seed: differences of a few points are within run-to-run noise (released teachers span ~10 pts on test).
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUNS, RES = REPO / "runs", REPO / "results"
DEBRIS = "Marine Debris"
ROWS = [("B (labels only, 80 rounds)", r"p2-B-w0\.25-s0-\d{8}-\d{4}$"),
        ("B-long (labels only, 160 rounds)", r"p2-Blong-w0\.25-s0-\d{8}-\d{4}$"),
        ("C (extra debris weight)", r"p3-C-w0\.25-s0-\d{8}-\d{4}$"),
        ("D (teacher, labelled px)", r"p3-D-w0\.25-s0-\d{8}-\d{4}$"),
        ("E (teacher, unlabelled px)", r"p3-E-w0\.25-s0-\d{8}-\d{4}$"),
        ("F (teacher, both + debris)", r"p3-F-w0\.25-s0-\d{8}-\d{4}$")]


def latest(regex):
    ds = sorted(d for d in RUNS.iterdir() if re.match(regex, d.name) and (d / "metrics.json").exists())
    return ds[-1] if ds else None


def main() -> None:
    out, L = [], ["# Distillation pilot — quarter width (318k params), seed 0\n",
                  "Generated by `scripts/summarise_kd_pilot.py`. One seed, KD settings at untuned defaults "
                  "(T = 2, τ = 0.8, λ_L = λ_U = 1, debris_w = 2 for F, C: debris CE weight ×2). Single-pass, labelled "
                  "pixels only. Model kept = best validation macro-F1 (EMA). **Pilot only:** with one seed, differences "
                  "of a few points can be noise.\n"]
    for split in ("val", "test"):
        L += [f"## {split}\n", "| version | run_id | kept round | debris F1 | debris recall | debris precision | debris IoU | macro-F1 | mIoU |",
              "|---|---|---|---|---|---|---|---|---|"]
        for name, rx in ROWS:
            d = latest(rx)
            if d is None:
                L.append(f"| {name} | (not run) | | | | | | | |"); continue
            m = json.loads((d / "metrics.json").read_text())
            r = m["results"][split]["single"]; db = r["per_class"][DEBRIS]
            row = {"version": name, "run_id": d.name, "split": split, "kept_round": m["selected_epoch"],
                   **{f"debris_{k}": round(100 * db[k], 1) for k in ("f1", "recall", "precision", "iou")},
                   "macro_f1": round(100 * r["macro_f1"], 1), "mIoU": round(100 * r["mIoU"], 1)}
            out.append(row)
            L.append(f"| {name} | `{d.name}` | {row['kept_round']} | {row['debris_f1']} | {row['debris_recall']} | "
                     f"{row['debris_precision']} | {row['debris_iou']} | {row['macro_f1']} | {row['mIoU']} |")
        L.append("")
    L += ["## Distillation diagnostics (last round)\n",
          "| version | KD on labelled px | KD on unlabelled px | share of unlabelled px used | teacher's class on used px (top 3) |",
          "|---|---|---|---|---|"]
    for name, rx in ROWS[3:]:
        d = latest(rx)
        if d is None:
            continue
        last = [json.loads(l) for l in (d / "epochs.jsonl").read_text().splitlines() if l.strip()][-1]["kd"]
        h = sorted(last["teacher_hist_ign"].items(), key=lambda kv: -kv[1])
        tot = sum(v for _, v in h) or 1
        top = ", ".join(f"{k} {100*v/tot:.1f}%" for k, v in h[:3])
        L.append(f"| {name} | {last['kd_lab']:.3f} | {last['kd_ign']:.3f} | {100*last['frac_ign_used']:.1f}% | {top} |")
    RES.mkdir(exist_ok=True)
    (RES / "kd_pilot.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    with open(RES / "kd_pilot.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0].keys())); w.writeheader(); w.writerows(out)
    print("\n".join(L))


if __name__ == "__main__":
    main()
