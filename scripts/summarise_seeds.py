"""3-seed summary at x0.25, 160 rounds → results/seeds_w0.25.{md,csv}.

Reads runs/: p2-Blong-w0.25-s{0,1,2}-*, p3-Clong-w0.25-s{0,1,2}-*, p3-F2-w0.25-s{0,1,2}-*.
Reports per-seed values, mean ± sample sd (n = 3), and per-seed differences to B-long
(same seed = same student initialisation and data order, so differences are paired).
"""
from __future__ import annotations

import csv
import json
import re
import statistics as st
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUNS, RES = REPO / "runs", REPO / "results"
DEBRIS = "Marine Debris"
SEEDS = (0, 1, 2)
METHODS = [("B-long", "labels only", "p2-Blong"),
           ("C-long", "debris errors count 2x", "p3-Clong"),
           ("F2", "teacher on labelled + unlabelled px, class-weighted, debris x2", "p3-F2")]
COLS = [("debris_f1", "debris F1"), ("debris_recall", "debris recall"), ("debris_precision", "debris precision"),
        ("debris_iou", "debris IoU"), ("macro_f1", "macro-F1"), ("mIoU", "mIoU")]


def latest(prefix: str, seed: int) -> Path | None:
    rx = re.compile(rf"{re.escape(prefix)}-w0\.25-s{seed}-\d{{8}}-\d{{4}}$")
    ds = sorted(d for d in RUNS.iterdir() if rx.match(d.name) and (d / "metrics.json").exists())
    return ds[-1] if ds else None


def scores(d: Path, split: str) -> dict:
    m = json.loads((d / "metrics.json").read_text())
    r = m["results"][split]["single"]; db = r["per_class"][DEBRIS]
    return {**{f"debris_{k}": 100 * db[k] for k in ("f1", "recall", "precision", "iou")},
            "macro_f1": 100 * r["macro_f1"], "mIoU": 100 * r["mIoU"], "kept_round": m["selected_epoch"]}


def ms(xs: list[float]) -> str:
    return f"{st.mean(xs):.1f} ± {st.stdev(xs):.1f}" if len(xs) > 1 else (f"{xs[0]:.1f}" if xs else "")


def main() -> None:
    runs = {name: {s: latest(pre, s) for s in SEEDS} for name, _, pre in METHODS}
    out, L = [], ["# Three seeds — quarter width (318k params), 160 rounds\n",
                  "Generated by `scripts/summarise_seeds.py`. Seeds 0, 1, 2; LR steps at rounds 90/130. "
                  "Model kept = best validation macro-F1 (EMA). Single-pass, labelled pixels only. "
                  "Values are mean ± sample sd over the seeds found (n shown).\n"]
    for name, desc, _ in METHODS:
        L.append(f"- **{name}**: {desc} — runs: " + ", ".join(f"`{d.name}`" if d else f"s{s} (not run)"
                                                            for s, d in runs[name].items()))
    L.append("")
    for split in ("val", "test"):
        per = {name: {s: scores(d, split) for s, d in runs[name].items() if d} for name, _, _ in METHODS}
        L += [f"## {split}: mean ± sd\n", "| method | n | " + " | ".join(c for _, c in COLS) + " |",
              "|---|---|" + "---|" * len(COLS)]
        for name, _, _ in METHODS:
            v = per[name]
            L.append(f"| {name} | {len(v)} | " + " | ".join(ms([x[k] for x in v.values()]) for k, _ in COLS) + " |")
            for s, x in v.items():
                out.append({"method": name, "seed": s, "split": split, "run_id": runs[name][s].name,
                            "kept_round": x["kept_round"], **{k: round(x[k], 2) for k, _ in COLS}})
        L += ["", f"## {split}: per seed (debris F1 / macro-F1)\n",
              "| method | " + " | ".join(f"seed {s}" for s in SEEDS) + " |", "|---|" + "---|" * len(SEEDS)]
        for name, _, _ in METHODS:
            L.append(f"| {name} | " + " | ".join(
                f"{per[name][s]['debris_f1']:.1f} / {per[name][s]['macro_f1']:.1f}" if s in per[name] else ""
                for s in SEEDS) + " |")
        L += ["", f"## {split}: paired difference to B-long (same seed), mean ± sd\n",
              "| method | debris F1 | debris recall | debris precision | macro-F1 | wins on debris F1 |", "|---|---|---|---|---|---|"]
        for name, _, _ in METHODS[1:]:
            common = [s for s in SEEDS if s in per[name] and s in per["B-long"]]
            diff = {k: [per[name][s][k] - per["B-long"][s][k] for s in common]
                    for k in ("debris_f1", "debris_recall", "debris_precision", "macro_f1")}
            wins = sum(x > 0 for x in diff["debris_f1"])
            L.append(f"| {name} − B-long | " + " | ".join(ms(diff[k]) for k in diff) + f" | {wins}/{len(common)} |")
        L.append("")
    RES.mkdir(exist_ok=True)
    (RES / "seeds_w0.25.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    with open(RES / "seeds_w0.25.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0].keys())); w.writeheader(); w.writerows(out)
    print("wrote results/seeds_w0.25.md")


if __name__ == "__main__":
    main()
