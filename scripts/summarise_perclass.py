"""Per-class degradation (which classes break first) → results/perclass.{md,csv}.

Per-class F1 (single pass, labelled pixels only), mean over seeds / released checkpoints, for the teacher and each
compressed model, and the change relative to the teacher. Sources as in ``summarise_headline.py``; INT8 rows use
the ONNX INT8 engine of ``runs/p4-H-*`` (plain = MinMax, tuned = percentile calibration + first/last conv FP32).
"""
from __future__ import annotations

import csv
import json
import re
import statistics as st
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
RUNS, RES = REPO / "runs", REPO / "results"

# (column label, regex over run names, engine)
MODELS = [("Teacher", r"p1-A-ckpt\d-envorig-\d{8}-\d{4}$", "single"),
          ("½ labels only", r"p2-Blong-w0\.5-s\d-\d{8}-\d{4}$", "single"),
          ("½ full method", r"p3-F2-w0\.5-s\d-\d{8}-\d{4}$", "single"),
          ("¼ labels only", r"p2-Blong-w0\.25-s\d-\d{8}-\d{4}$", "single"),
          ("¼ full method", r"p3-F2-w0\.25-s\d-\d{8}-\d{4}$", "single"),
          ("⅛ labels only (80 rounds)", r"p2-B-w0\.125-s\d-\d{8}-\d{4}$", "single"),
          ("Teacher INT8 plain", r"p4-H-A-ckpt\d-\d{8}-\d{4}$", "onnx_int8"),
          ("Teacher INT8 tuned", r"p4-H-A-ckpt\d-qpctends-\d{8}-\d{4}$", "onnx_int8")]


def runs_for(regex: str):
    """Newest complete, non-smoke run per model key (seed or checkpoint)."""
    out = {}
    for d in sorted(RUNS.iterdir()):
        if not (re.match(regex, d.name) and (d / "metrics.json").exists()):
            continue
        cfg = d / "config.yaml"
        if cfg.exists() and (yaml.safe_load(cfg.read_text()) or {}).get("subset"):
            continue
        m = json.loads((d / "metrics.json").read_text())
        if "test" in m.get("results", {}):
            out[re.sub(r"-\d{8}-\d{4}$", "", d.name)] = m
    return list(out.values())


def main() -> None:
    data, n = {}, {}
    for label, rx, eng in MODELS:
        ms = runs_for(rx)
        n[label] = len(ms)
        data[label] = {s: [m["results"][s][eng] for m in ms] for s in ("val", "test")}
    classes = list(data["Teacher"]["val"][0]["per_class"])
    L = ["# Per-class F1: which classes break first\n",
         "Generated by `scripts/summarise_perclass.py`. Single pass, labelled pixels only. F1 in %, mean over "
         "seeds (students) or the 5 released checkpoints (teacher); n = " + ", ".join(f"{k} {v}" for k, v in n.items())
         + ". Δ = change vs the teacher. Students trained 160 rounds unless noted. Classes sorted by number of "
         "labelled validation pixels (support). Classes with very few pixels give noisy F1.\n"]
    rows = []
    for s in ("val", "test"):
        sup = {c: data["Teacher"][s][0]["per_class"][c]["support"] for c in classes}
        order = sorted(classes, key=lambda c: -sup[c])
        mean = {lb: {c: 100 * st.mean(r["per_class"][c]["f1"] for r in data[lb][s]) for c in classes}
                for lb, _, _ in MODELS if data[lb][s]}
        cols = [lb for lb, _, _ in MODELS if lb in mean]
        L += [f"## {s}: F1 per class (Δ vs teacher)\n",
              "| class | labelled px | " + " | ".join(cols) + " |", "|---|---|" + "---|" * len(cols)]
        for c in order:
            t = mean["Teacher"][c]
            cells = [f"{t:.1f}"] + [f"{mean[lb][c]:.1f} ({mean[lb][c] - t:+.1f})" for lb in cols[1:]]
            L.append(f"| {c} | {sup[c]:,} | " + " | ".join(cells) + " |")
            for lb in cols:
                rows.append({"split": s, "class": c, "support": sup[c], "model": lb, "n": n[lb],
                             "f1": round(mean[lb][c], 2), "delta_vs_teacher": round(mean[lb][c] - t, 2)})
        for lb in cols[1:]:
            d = sorted(classes, key=lambda c: mean[lb][c] - mean["Teacher"][c])
            L.append(f"\n- {lb}: largest drops — " + ", ".join(
                f"{c} {mean[lb][c] - mean['Teacher'][c]:+.1f}" for c in d[:3]))
        L.append("")
    RES.mkdir(exist_ok=True)
    (RES / "perclass.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    with open(RES / "perclass.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    print("wrote results/perclass.md")


if __name__ == "__main__":
    main()
