"""Efficiency summary: latest runs/p4-bench-laptop-*/metrics.json + finished sweep runs → results/efficiency.{csv,md}
and results/fig_accuracy_vs_latency.{png,pdf}. Accuracy columns come from train.py metrics.json (val + test,
single pass); the teacher row uses the 5 released checkpoints (mean ± sd)."""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import matplotlib.ticker  # noqa: E402
import numpy as np  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
RUNS, RES = REPO / "runs", REPO / "results"
DEBRIS = "Marine Debris"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]
INK, INK2, MUTED, GRID = "#0b0b0b", "#52514e", "#898781", "#e6e5e1"
plt.rcParams.update({"font.size": 10, "axes.edgecolor": MUTED, "axes.labelcolor": INK2, "xtick.color": INK2,
                     "ytick.color": INK2, "axes.grid": True, "grid.color": GRID, "axes.spines.top": False,
                     "axes.spines.right": False, "legend.frameon": False, "savefig.dpi": 200, "savefig.bbox": "tight"})


def main() -> None:
    bench_dirs = sorted(d for d in RUNS.glob("p4-bench-laptop-*") if (d / "metrics.json").exists())
    if not bench_dirs:
        raise SystemExit("no benchmark run found")
    bench = json.loads((bench_dirs[-1] / "metrics.json").read_text())
    acc = {}
    for d in sorted(RUNS.glob("p2-B-w*-s0-*")):
        if (d / "metrics.json").exists():
            m = json.loads((d / "metrics.json").read_text())
            acc[m["width"]] = (m["run_id"], {s: 100 * m["results"][s]["single"]["per_class"][DEBRIS]["f1"] for s in ("val", "test")})
    rel = []
    for d in sorted(RUNS.glob("p1-A-ckpt*-envorig-*")):
        if re.search(r"ckpt\d-envorig-\d{8}-\d{4}$", d.name):
            r = json.loads((d / "metrics.json").read_text())["results"]
            rel.append({s: 100 * r[s]["single"]["per_class"][DEBRIS]["f1"] for s in ("val", "test")})
    rows = []
    for w, b in bench["models"].items():
        w = float(w)
        if w == 1.0 and rel:
            src, f1v, f1t = "released ckpts 1–5 (mean)", np.mean([r["val"] for r in rel]), np.mean([r["test"] for r in rel])
        elif w in acc:
            src, f1v, f1t = acc[w][0], acc[w][1]["val"], acc[w][1]["test"]
        else:
            src, f1v, f1t = "", float("nan"), float("nan")
        rows.append({"width": w, "params": b["params"], "macs_conv_linear_G": round(b["conv_linear"] / 1e9, 3),
                     "state_dict_MB": round(b["state_dict_bytes"] / 2**20, 2),
                     "gpu_median_ms": round(b["gpu"]["median_ms"], 2) if "gpu" in b else "",
                     "gpu_p90_ms": round(b["gpu"]["p90_ms"], 2) if "gpu" in b else "",
                     "gpu_peak_MB": round(b["gpu"]["peak_mem_mb"], 1) if "gpu" in b else "",
                     **{f"cpu{n}t_median_ms": round(b[f"cpu_{n}t"]["median_ms"], 1) for n in (8, 1) if f"cpu_{n}t" in b},
                     "debris_f1_val": round(f1v, 1), "debris_f1_test": round(f1t, 1), "accuracy_source": src,
                     "bench_run": bench["run_id"]})
    RES.mkdir(exist_ok=True)
    with open(RES / "efficiency.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader(); w.writerows(rows)
    L = ["# Efficiency — laptop (RTX 4060 Laptop GPU, CPU in WSL2)\n",
         f"Generated by `scripts/summarise_efficiency.py` from `{bench['run_id']}` and the sweep runs. Batch 1, "
         "1×11×240×240, FP32, 50 warm-up + 200 timed, median of 3 medians. Debris F1 = single pass, setting B "
         "(seed 0) or the mean of the 5 released teachers. MACs exclude the decoder's NMF matrix products.\n",
         "| width | params | GMACs | FP32 size (MB) | GPU ms (p90) | GPU peak MB | CPU 8 thr ms | CPU 1 thr ms | debris F1 val | debris F1 test |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| ×{r['width']:g} | {r['params']:,} | {r['macs_conv_linear_G']} | {r['state_dict_MB']} | "
                 f"{r['gpu_median_ms']} ({r['gpu_p90_ms']}) | {r['gpu_peak_MB']} | {r.get('cpu8t_median_ms','')} | "
                 f"{r.get('cpu1t_median_ms','')} | {r['debris_f1_val']} | {r['debris_f1_test']} |")
    (RES / "efficiency.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    pts = [r for r in rows if r["debris_f1_val"] == r["debris_f1_val"]]
    if pts and "cpu1t_median_ms" in rows[0]:
        fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=True)
        for ax, key, lab in ((axes[0], "cpu1t_median_ms", "CPU, 1 thread"), (axes[1], "gpu_median_ms", "RTX 4060 Laptop GPU")):
            xs = [r[key] for r in pts]
            ys = [r["debris_f1_val"] for r in pts]
            ax.plot(xs, ys, "-o", color=SERIES[0], lw=2, ms=8, mec="white", mew=2)
            for r in pts:
                ax.annotate(f"×{r['width']:g}", (r[key], r["debris_f1_val"]), textcoords="offset points", xytext=(0, 9),
                            ha="center", color=INK2)
            if key.startswith("cpu"):
                ax.set_xscale("log")
                ax.set_xticks([10, 20, 40, 80]); ax.set_xticks([], minor=True)
                ax.xaxis.set_major_formatter(matplotlib.ticker.ScalarFormatter())
            ax.set_xlabel(f"latency per image, ms ({lab})")
        axes[0].set_ylabel("validation debris F1 (%)")
        fig.suptitle("Debris F1 vs latency (×1 = released teachers, others = setting B)", x=0.06, ha="left",
                     color=INK, fontweight="bold")
        for ext in ("png", "pdf"):
            fig.savefig(RES / f"fig_accuracy_vs_latency.{ext}")
        plt.close(fig)
    print("wrote results/efficiency.{csv,md}")


if __name__ == "__main__":
    main()
