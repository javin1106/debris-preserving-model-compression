"""Phase 2.5 summary: width sweep (setting B) → results/width_sweep.{csv,md} + figures.

Reads only runs/:
  runs/p2-B-w<width>-s<seed>-*/  (train.py: metrics.json when finished, epochs.jsonl while training)
  runs/p1-A-w1.0-s<seed>-*/      (our retrained teacher, same train.py, optional)
  runs/p1-A-ckpt<k>-envorig-<ts>/ (released checkpoints, reference)
Finished runs (metrics.json) go into the tables. Unfinished runs appear only in the training-curve figure,
clearly marked "in progress". Model selection = EMA weights at best val macro-F1 (decision 2026-10-15).
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path
from typing import Dict, List

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
RUNS, RES = REPO / "runs", REPO / "results"
DEBRIS = "Marine Debris"
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7", "#e34948"]
INK, INK2, MUTED, GRID = "#0b0b0b", "#52514e", "#898781", "#e6e5e1"
plt.rcParams.update({"font.size": 10, "axes.edgecolor": MUTED, "axes.labelcolor": INK2, "xtick.color": INK2,
                     "ytick.color": INK2, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8,
                     "axes.spines.top": False, "axes.spines.right": False, "legend.frameon": False,
                     "savefig.dpi": 200, "savefig.bbox": "tight"})


def latest(pattern: str, regex: str) -> Dict[str, Path]:
    out: Dict[str, Path] = {}
    for d in sorted(RUNS.glob(pattern)):
        m = re.match(regex, d.name)
        if m:
            out[m.group(1)] = d
    return out


def trained_runs() -> Dict[str, Path]:
    """key 'w<width>-s<seed>' → latest run dir (setting B students + our retrained teacher)."""
    runs = {f"w{k}": v for k, v in latest("p2-B-w*", r"p2-B-w([\d.]+-s\d+)-\d{8}-\d{4}$").items()}
    runs.update({f"w{k}": v for k, v in latest("p1-A-w1.0-s*", r"p1-A-w(1\.0-s\d+)-\d{8}-\d{4}$").items()})
    return dict(sorted(runs.items(), key=lambda kv: -float(kv[0][1:].split("-s")[0])))


def released() -> Dict:
    """Released checkpoints: mean ± sd over the 5, per split/mode, debris + macro + per-class F1."""
    runs = latest("p1-A-ckpt*-envorig-*", r"p1-A-ckpt(\d)-envorig-\d{8}-\d{4}$")
    data = [json.loads((d / "metrics.json").read_text())["results"] for d in runs.values()]
    out = {"n": len(data), "run_ids": [d.name for d in runs.values()]}
    for split in ("val", "test"):
        for mode in ("single", "tta"):
            rs = [d[split][mode] for d in data]
            out[(split, mode)] = {
                "debris_f1": [100 * r["per_class"][DEBRIS]["f1"] for r in rs],
                "debris_recall": [100 * r["per_class"][DEBRIS]["recall"] for r in rs],
                "debris_iou": [100 * r["per_class"][DEBRIS]["iou"] for r in rs],
                "mIoU": [100 * r["mIoU"] for r in rs], "macro_f1": [100 * r["macro_f1"] for r in rs],
                "class_f1": {c: [100 * r["per_class"][c]["f1"] for r in rs] for c in rs[0]["per_class"]}}
    return out


def ms(x: List[float]) -> str:
    a = np.asarray(x)
    return f"{a.mean():.1f} ± {a.std(ddof=1):.1f}" if len(a) > 1 else f"{a.mean():.1f}"


def main() -> None:
    RES.mkdir(exist_ok=True)
    runs = trained_runs()
    rel = released()
    done = {k: json.loads((d / "metrics.json").read_text()) for k, d in runs.items() if (d / "metrics.json").exists()}
    classes = list(rel[("val", "single")]["class_f1"])

    # ---------------- CSV (finished runs) ----------------
    rows = []
    for k, m in done.items():
        for split in ("val", "test"):
            for mode in ("single", "tta"):
                r = m["results"][split][mode]
                d = r["per_class"][DEBRIS]
                row = {"run_id": m["run_id"], "width": m["width"], "seed": m["seed"], "params": m["params"],
                       "selected_epoch": m["selected_epoch"], "split": split, "mode": mode,
                       "debris_f1": round(100 * d["f1"], 2), "debris_recall": round(100 * d["recall"], 2),
                       "debris_iou": round(100 * d["iou"], 2), "debris_precision": round(100 * d["precision"], 2),
                       "mIoU": round(100 * r["mIoU"], 2), "macro_f1": round(100 * r["macro_f1"], 2)}
                row.update({f"f1_{c}": round(100 * r["per_class"][c]["f1"], 2) for c in classes})
                rows.append(row)
    if rows:
        with open(RES / "width_sweep.csv", "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader(); w.writerows(rows)

    # ---------------- Markdown ----------------
    L = ["# Width sweep — setting B (official recipe, labels only)\n",
         "Generated by `scripts/summarise_sweep.py` from `runs/`. Model selection: EMA weights at the epoch with the "
         "best **validation** macro-F1. Metrics on labelled pixels only. Single = one forward pass (headline); "
         "TTA = official 8-view vote. Released-checkpoint reference = mean ± sd over the 5 released MariNeXt models "
         f"({', '.join(rel['run_ids'])}).\n"]
    for split in ("val", "test"):
        L.append(f"## {split} split\n")
        L.append("| model | run_id | params | sel. epoch | debris F1 | debris recall | debris IoU | mIoU | macro-F1 | debris F1 (TTA) |")
        L.append("|---|---|---|---|---|---|---|---|---|---|")
        rs, rt = rel[(split, "single")], rel[(split, "tta")]
        L.append(f"| released teacher ×5 | (5 runs) | 4,238,063 | – | {ms(rs['debris_f1'])} | {ms(rs['debris_recall'])} | "
                 f"{ms(rs['debris_iou'])} | {ms(rs['mIoU'])} | {ms(rs['macro_f1'])} | {ms(rt['debris_f1'])} |")
        for k, m in done.items():
            r, t = m["results"][split]["single"], m["results"][split]["tta"]
            d = r["per_class"][DEBRIS]
            name = "retrained teacher" if m["width"] == 1.0 else f"student ×{m['width']}"
            L.append(f"| {name} (seed {m['seed']}) | `{m['run_id']}` | {m['params']:,} | {m['selected_epoch']} | "
                     f"{100*d['f1']:.1f} | {100*d['recall']:.1f} | {100*d['iou']:.1f} | {100*r['mIoU']:.1f} | "
                     f"{100*r['macro_f1']:.1f} | {100*t['per_class'][DEBRIS]['f1']:.1f} |")
        L.append("")
    if done:
        L.append("## Per-class F1, validation, single-pass\n")
        hdr = "| class | released ×5 | " + " | ".join(f"×{m['width']}" for m in done.values()) + " |"
        L += [hdr, "|---|---|" + "---|" * len(done)]
        for c in classes:
            L.append(f"| {c} | {ms(rel[('val','single')]['class_f1'][c])} | " + " | ".join(
                f"{100*m['results']['val']['single']['per_class'][c]['f1']:.1f}" for m in done.values()) + " |")
        L.append("")
    pending = [d.name for k, d in runs.items() if k not in done]
    if pending:
        L.append("**Still training (not in the tables):** " + ", ".join(f"`{p}`" for p in pending) + "\n")
    (RES / "width_sweep.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    # ---------------- Figure 1: debris F1 vs params ----------------
    if done:
        fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=True)
        for ax, split in zip(axes, ("val", "test")):
            pts = sorted(((m["params"], 100 * m["results"][split]["single"]["per_class"][DEBRIS]["f1"], m["width"])
                          for m in done.values() if m["width"] != 1.0))
            if pts:
                ax.plot([p[0] for p in pts], [p[1] for p in pts], "-o", color=SERIES[0], lw=2, ms=8,
                        mec="white", mew=2, label="student (setting B, seed 0)", zorder=3)
                for p, f, wd in pts:
                    ax.annotate(f"×{wd:g}", (p, f), textcoords="offset points", xytext=(0, 9), ha="center", color=INK2)
            r = np.asarray(rel[(split, "single")]["debris_f1"])
            ax.errorbar([4_238_063], [r.mean()], yerr=[r.std(ddof=1)], fmt="s", color=SERIES[1], ms=8, mec="white",
                        mew=2, capsize=4, lw=2, label="released teacher (mean ± sd, 5)", zorder=3)
            for m in done.values():
                if m["width"] == 1.0:
                    ax.plot([m["params"] * 1.12], [100 * m["results"][split]["single"]["per_class"][DEBRIS]["f1"]], "D",
                            color=SERIES[2], ms=8, mec="white", mew=2, label="our retrained teacher", zorder=3)
            ax.set_xscale("log"); ax.set_xlabel("parameters (log scale)")
            ax.set_title(f"{split} split", color=INK, loc="left")
        axes[0].set_ylabel("Marine Debris F1 (%), single pass")
        axes[1].legend(loc="lower right")
        fig.suptitle("Debris F1 vs model size", x=0.06, ha="left", color=INK, fontweight="bold")
        for ext in ("png", "pdf"):
            fig.savefig(RES / f"fig_width_sweep.{ext}")
        plt.close(fig)

        # ---------------- Figure 2: per-class F1 change vs teacher (val) ----------------
        studs = [m for m in done.values() if m["width"] != 1.0]
        if studs:
            base = {c: np.mean(rel[("val", "single")]["class_f1"][c]) for c in classes}
            delta = np.array([[100 * m["results"]["val"]["single"]["per_class"][c]["f1"] - base[c] for m in studs]
                              for c in classes])
            order = np.argsort(delta[:, -1])
            fig, ax = plt.subplots(figsize=(1.2 * len(studs) + 4.5, 6))
            lim = max(10, np.abs(delta).max())
            im = ax.imshow(delta[order], cmap="RdBu", vmin=-lim, vmax=lim, aspect="auto")
            ax.set_yticks(range(len(classes))); ax.set_yticklabels([classes[i] for i in order])
            ax.set_xticks(range(len(studs))); ax.set_xticklabels([f"×{m['width']:g}\n{m['params']/1e3:.0f}k" for m in studs])
            ax.grid(False)
            for i, ci in enumerate(order):
                for j in range(len(studs)):
                    v = delta[ci, j]
                    ax.text(j, i, f"{v:+.0f}", ha="center", va="center", fontsize=8,
                            color="white" if abs(v) > 0.6 * lim else INK)
            cb = fig.colorbar(im, ax=ax, shrink=0.8); cb.set_label("F1 change vs released teacher (pts)")
            ax.set_title("Per-class F1 change, validation (sorted by smallest model)", loc="left", color=INK)
            for ext in ("png", "pdf"):
                fig.savefig(RES / f"fig_width_sweep_perclass.{ext}")
            plt.close(fig)

    # ---------------- Figure 3: training curves (all runs, incl. in progress) ----------------
    curves = {}
    for k, d in runs.items():
        f = d / "epochs.jsonl"
        if f.exists():
            recs = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
            if recs:
                curves[k] = (d.name, recs, (d / "metrics.json").exists())
    if curves:
        fig, axes = plt.subplots(1, 2, figsize=(10, 3.8))
        for i, (k, (rid, recs, fin)) in enumerate(curves.items()):
            ep = [r["epoch"] for r in recs]
            lab = f"{k.split('-s')[0].replace('w', '×')}" + ("" if fin else " (in progress)")
            axes[0].plot(ep, [100 * r["val_ema"]["debris_f1"] for r in recs], color=SERIES[i % 8], lw=2, label=lab)
            axes[1].plot(ep, [100 * r["val_ema"]["macro_f1"] for r in recs], color=SERIES[i % 8], lw=2, label=lab)
        axes[0].set_ylabel("val debris F1 (%), EMA"); axes[1].set_ylabel("val macro-F1 (%), EMA")
        for ax in axes:
            ax.set_xlabel("epoch"); ax.axvline(45, color=MUTED, lw=1, ls=":"); ax.axvline(65, color=MUTED, lw=1, ls=":")
        axes[1].legend(loc="lower right")
        fig.suptitle("Validation curves during training (dotted: LR drops)", x=0.06, ha="left", color=INK, fontweight="bold")
        for ext in ("png", "pdf"):
            fig.savefig(RES / f"fig_training_curves.{ext}")
        plt.close(fig)
    print(f"finished runs: {len(done)}, in progress: {len(pending)}; wrote results/width_sweep.md and figures")


if __name__ == "__main__":
    main()
